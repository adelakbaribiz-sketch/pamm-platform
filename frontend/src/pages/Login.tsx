import React, { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { api } from '../api'
import { useAuth } from '../auth'
import { Brand } from '../components/Layout'
import { Icon } from '../components/icons'

// Seeded demo users (see backend/app/seed.py and demo_history.py). Not real credentials.
const DEMO_PASSWORD = 'Demo1234!'
const DEMO_ACCOUNTS = [
  { email: 'broker@demo.com', role: 'Broker Admin', desc: 'Full back-office: masters, investors, rollovers, infrastructure' },
  { email: 'manager@demo.com', role: 'Money Manager', desc: 'Manager desk, strategy performance, MAM & copy' },
  { email: 'investor1@demo.com', role: 'Investor', desc: 'Personal portfolio across three strategies' },
  { email: 'compliance@demo.com', role: 'Compliance', desc: 'Settlement proofs and saga audit trail' },
]

const LANDING_BY_ROLE: Record<string, string> = {
  investor: '/investor-workspace', money_manager: '/manager-workspace', compliance: '/settlement',
}

export default function Login() {
  const [email, setEmail] = useState('broker@demo.com')
  const [password, setPassword] = useState(DEMO_PASSWORD)
  const [err, setErr] = useState('')
  const [busy, setBusy] = useState(false)
  const { setSession } = useAuth()
  const nav = useNavigate()

  async function signIn(em: string, pw: string) {
    setBusy(true); setErr('')
    try {
      const t = await api.login(em, pw)
      setSession({ access_token: t.access_token, role: t.role, tenant_id: t.tenant_id, user_id: t.user_id, email: em })
      nav(LANDING_BY_ROLE[t.role] || '/')
    } catch (e: any) {
      setErr(e.message === 'Failed to fetch' ? 'Cannot reach the API. Is the backend running on port 8000?' : e.message)
    } finally { setBusy(false) }
  }

  const emailInvalid = email.length > 0 && !/^\S+@\S+\.\S+$/.test(email)

  return (
    <div className="min-h-screen grid lg:grid-cols-[1.1fr_1fr] bg-bg">
      <div className="hidden lg:flex flex-col justify-between p-10 border-r border-line bg-surface relative overflow-hidden">
        <Brand />
        <div className="max-w-lg relative">
          <div className="text-[11px] font-semibold uppercase tracking-wider text-brand-500 mb-3">PAMM · MAM · Copy trading</div>
          <h1 className="text-4xl font-semibold tracking-tight leading-tight">Transparent pooled-account allocation for brokers, managers and investors.</h1>
          <p className="text-muted mt-4 leading-relaxed">
            Unit-based NAV accounting, high-water-mark performance fees, Merkle-verifiable settlement statements
            and a tamper-evident audit chain — in one multi-tenant back office.
          </p>
          <ul className="mt-8 space-y-3 text-sm">
            {['Decimal-exact allocation: euro-days, start or end capital', 'Per-investor Merkle proofs for every rollover', 'Broker-agnostic adapters (MT5, cTrader, crypto) — simulated here'].map(t => (
              <li key={t} className="flex items-center gap-3"><span className="w-5 h-5 rounded-full bg-gain/15 text-gain grid place-items-center"><Icon name="check" className="w-3 h-3" strokeWidth={2.5} /></span>{t}</li>
            ))}
          </ul>
        </div>
        <p className="text-xs text-subtle">Prototype build. Performance figures are generated by a simulated broker and are not real results.</p>
      </div>

      <div className="flex items-center justify-center p-6 sm:p-10">
        <div className="w-full max-w-md">
          <div className="lg:hidden mb-8"><Brand /></div>
          <h2 className="text-2xl font-semibold tracking-tight">Sign in</h2>
          <p className="text-sm text-muted mt-1 mb-6">Use a demo workspace below or enter credentials.</p>
          <form onSubmit={e => { e.preventDefault(); if (!emailInvalid) signIn(email, password) }} className="space-y-4" noValidate>
            <label className="block">
              <span className="label">Email</span>
              <input className={`input ${emailInvalid ? 'input-error' : ''}`} type="email" autoComplete="username" value={email} onChange={e => setEmail(e.target.value)} />
              {emailInvalid && <span className="block text-xs text-loss mt-1">Enter a valid email address</span>}
            </label>
            <label className="block">
              <span className="label">Password</span>
              <input type="password" autoComplete="current-password" className="input" value={password} onChange={e => setPassword(e.target.value)} />
            </label>
            {err && <div className="flex items-start gap-2 rounded-lg border border-loss/30 bg-loss/5 px-3 py-2 text-sm text-loss"><Icon name="alert" className="w-4 h-4 mt-0.5" />{err}</div>}
            <button disabled={busy || !email || !password} className="btn-primary w-full h-10">{busy ? 'Signing in…' : 'Sign in'}</button>
          </form>

          <div className="mt-8">
            <div className="flex items-center gap-3 mb-3">
              <span className="text-[11px] font-semibold uppercase tracking-wider text-subtle">Demo workspaces</span>
              <span className="flex-1 h-px bg-line" />
            </div>
            <div className="grid gap-2">
              {DEMO_ACCOUNTS.map(a => (
                <button key={a.email} type="button" disabled={busy} onClick={() => { setEmail(a.email); setPassword(DEMO_PASSWORD); signIn(a.email, DEMO_PASSWORD) }}
                  className="card text-left px-4 py-3 hover:border-brand-500/50 transition-colors flex items-center gap-3 group">
                  <div className="flex-1 min-w-0">
                    <div className="text-sm font-medium">{a.role} <span className="text-subtle font-normal">· {a.email}</span></div>
                    <div className="text-xs text-muted truncate">{a.desc}</div>
                  </div>
                  <Icon name="chevronRight" className="w-4 h-4 text-subtle group-hover:text-brand-500" />
                </button>
              ))}
            </div>
            <p className="text-[11px] text-subtle mt-3">Demo password for all seeded accounts: <span className="font-mono">{DEMO_PASSWORD}</span></p>
          </div>
        </div>
      </div>
    </div>
  )
}
